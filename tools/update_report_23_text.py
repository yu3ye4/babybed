def main() -> None:
    doc = Document(str(DOC_PATH))

    for idx, text in REPLACEMENTS.items():
        doc.paragraphs[idx].text = text

    for idx, paras in sorted(INSERT_AFTER.items(), reverse=True):
        parent = doc.paragraphs[idx]._p.getparent()
        pos = parent.index(doc.paragraphs[idx]._p)
        for offset, text in enumerate(paras, start=1):
            p = doc.add_paragraph(text)
            new_p = p._p
            parent.remove(new_p)
            parent.insert(pos + offset, new_p)

    doc.save(str(DOC_PATH))


if __name__ == "__main__":
    main()
